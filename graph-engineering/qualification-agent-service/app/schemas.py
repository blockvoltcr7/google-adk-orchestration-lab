from __future__ import annotations

from typing import Any, Optional
from pydantic import BaseModel, Field

class LeadMetadata(BaseModel):
    """Optional context attributes about the lead."""
    company: Optional[str] = None
    company_size: Optional[int] = None
    industry: Optional[str] = None
    budget_range: Optional[str] = None
    current_crm: Optional[str] = None
    lead_source: Optional[str] = "inbound_web"

class InboundLeadPayload(BaseModel):
    """
    The incoming payload sent on every inbound user interaction.
    - `message` is passed to the LLM turn as conversational input.
    - `user_id`, `contact_id`, `calendar_id`, and `metadata` are injected
      into ADK Session State without polluting prompt context tokens.
    """
    user_id: str = Field(..., description="Unique ID for the end user")
    contact_id: str = Field(..., description="CRM Contact ID associated with the lead")
    calendar_id: str = Field(..., description="Target Google Calendar ID for booking qualification meetings")
    message: str = Field(..., description="User message or query")
    metadata: Optional[dict[str, Any]] = Field(
        default_factory=dict,
        description="Arbitrary lead attributes (company, size, budget, etc.)"
    )

class LeadQualificationReport(BaseModel):
    """Structured qualification assessment generated by the agent."""
    is_qualified: bool = Field(description="Whether the lead meets qualification criteria")
    tier: str = Field(description="ENTERPRISE | MID_MARKET | SMB | UNQUALIFIED")
    score: int = Field(ge=0, le=100, description="Lead score from 0 to 100")
    key_drivers: list[str] = Field(description="Key reasons supporting the qualification score")
    next_step: str = Field(description="Recommended next step (e.g. Schedule Demo, Route to Sales)")

class AgentResponse(BaseModel):
    """Response returned by the FastAPI service to the caller."""
    response_text: str
    session_id: str
    qualification_status: Optional[str] = "PENDING"
    meeting_booked: bool = False
    session_state_snapshot: dict[str, Any]
